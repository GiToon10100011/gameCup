// getRoundName 유틸 단위 테스트 — Task #36 (F-07 라운드 명칭)
//
// 검증 범위:
//   1) 2명 → "결승"
//   2) 4명 → "4강"
//   3) 8명 → "8강"
//   4) 16명 → "16강"
//   5) 32명 이상의 큰 수 → "${n}강"
//   6) 비정상 값 (0 이하, 1) → ""

import { describe, expect, it } from "vitest";
import { getRoundName } from "@/utils/roundName";

describe("getRoundName (Task #36, F-07)", () => {
  // ─────────────────────────────────────────────────────────────────────────
  // 정상 경로 — 주요 토너먼트 크기
  // ─────────────────────────────────────────────────────────────────────────

  it("2명이면 '결승'을 반환한다", () => {
    expect(getRoundName(2)).toBe("결승");
  });

  it("4명이면 '4강'을 반환한다", () => {
    expect(getRoundName(4)).toBe("4강");
  });

  it("8명이면 '8강'을 반환한다", () => {
    expect(getRoundName(8)).toBe("8강");
  });

  it("16명이면 '16강'을 반환한다", () => {
    expect(getRoundName(16)).toBe("16강");
  });

  it("32명이면 '32강'을 반환한다", () => {
    expect(getRoundName(32)).toBe("32강");
  });

  // ─────────────────────────────────────────────────────────────────────────
  // 홀수 참가자 (부전승 발생 시나리오)
  // ─────────────────────────────────────────────────────────────────────────

  it("3명이면 '3강'을 반환한다 (부전승 발생 시)", () => {
    expect(getRoundName(3)).toBe("3강");
  });

  it("5명이면 '5강'을 반환한다 (부전승 발생 시)", () => {
    expect(getRoundName(5)).toBe("5강");
  });

  // ─────────────────────────────────────────────────────────────────────────
  // 비정상 입력 방어 (토너먼트 구조상 발생 불가)
  // ─────────────────────────────────────────────────────────────────────────

  it("1명이면 빈 문자열을 반환한다", () => {
    expect(getRoundName(1)).toBe("");
  });

  it("0 이하면 빈 문자열을 반환한다", () => {
    expect(getRoundName(0)).toBe("");
    expect(getRoundName(-1)).toBe("");
  });
});
